(* ## 7.1 演算子は糖衣である — ただし脱糖はしない

   Keleut にユーザ定義演算子はありません。代わりに sample.kel:348-353 が
   「組み込みの演算子が標準ライブラリの型クラスを呼ぶ」と決めています。

   | 演算子 | 意味 |
   |---|---|
   | `+` `-` `*` `/` | `Add.add` `Sub.sub` `Mul.mul` `Div.div` |
   | `==` | `Eq.eq` |
   | `!=` | `Eq.eq` の否定 |
   | `<` `<=` `>` `>=` | `Ord.lt` `Ord.le` `Ord.gt` `Ord.ge` |
   | `&&` `\|\|` | Boolean 組み込み(短絡するため型クラスにできない) |

   つまり演算子は糖衣です。ところが本実装は**パーサで脱糖しません**。
   `BinOp` ノードを AST に残し、elab と interp がこの表を引きます
   (裁定 D9)。理由は 2 つ。

   - **エラーメッセージが演算子を保てる。** 脱糖した木はソースに戻せません。
     `x + y` の診断を「`Add.add` の引数が」ではなく `+` の話として出せる
     余地を残す、というのが D9 の理由づけです(現状の診断は型の不一致を
     述べるところまでで、この余地はまだ使い切っていません)。
   - **2 つの例外が表の中に閉じる。** `&&` / `||` と `!=` は、
     メソッド呼び出しに落とせません(後述)。脱糖する設計だと、この 2 つだけ
     パーサに特別扱いが要ります。表なら 3 番目のコンストラクタで済みます。

   ### なぜ `&&` と `||` は型クラスにできないか

   **短絡するから**です。`a && b` をメソッド呼び出し `and(a, b)` に落とすと、
   呼び出しの前に両辺が評価されます。短絡は評価順序の話で、型クラスは
   値の話なので、そもそも層が違う。だから `OpBool` として組み込みに残し、
   第14章が左辺だけを見て分岐します。両辺 Boolean であることの検査は
   第11章がやります。

   ### なぜ `!=` に専用のクラスを作らないか

   `OpMethodNot` は `Eq.eq` を呼んで結果を否定するだけです。**型の上では
   `!=` は `==` と完全に同一**で、第11章は両者を同じ 1 本の枝で処理します
   — `Eq.eq` のスキーマを具体化して単一化し、その返り型(Boolean)を返す。
   違いは第14章での否定 1 回だけです。

   `Ne` を独立のクラスにすれば「`==` と `!=` が食い違うインスタンス」が
   書けてしまいます。導出のたびに 2 つ書く手間も増える。**書けない設計に
   することで、一致を検査する必要がなくなります。**

   ### この表にいないもの

   単項の `!` は二項演算子ではないので、第1章の AST に専用ノード `Not` が
   あります。行の制限 `\` は組み込み構文(`RecordRestriction`)で、
   これもメソッドではありません。表に入れる基準は
   「二項演算子の形をしていて、意味がクラスメソッドで書けるもの」です。 *)

type op_sem =
  | OpMethod of string * string (* クラス名, メソッド名 *)
  | OpMethodNot of string * string (* Eq.eq の否定(!=) *)
  | OpBool (* Boolean 組み込み(短絡するため型クラスにできない) *)

let bin_op_sem = function
  | Add -> OpMethod ("Add", "add")
  | Sub -> OpMethod ("Sub", "sub")
  | Mul -> OpMethod ("Mul", "mul")
  | Div -> OpMethod ("Div", "div")
  | Eq -> OpMethod ("Eq", "eq")
  | Ne -> OpMethodNot ("Eq", "eq")
  | Lt -> OpMethod ("Ord", "lt")
  | Le -> OpMethod ("Ord", "le")
  | Gt -> OpMethod ("Ord", "gt")
  | Ge -> OpMethod ("Ord", "ge")
  | And | Or -> OpBool

(* ## 7.2 字面へ戻す

   `bin_op_sem` が演算子を意味へ写すのに対し、こちらは字面へ戻します。
   前節で「保てる」と書いた演算子を人に見せるための 1 枚で、`BinOp` を
   AST に残した選択は、この表があって初めて回収できます。

   引くのは第4章 (dump.ml) の `BinOp` ダンプです (M19 / G2 で一本化)。
   `--dump-ast` の演算子表記と、いつか診断に出す演算子表記が、同じ
   1 枚から出ます。かつては dump 側が同じ表を自前に持つ二重定義で、
   演算子を 1 つ足す日に 2 箇所直す負債でした。 *)

let show_bin_op = function
  | Add -> "+"
  | Sub -> "-"
  | Mul -> "*"
  | Div -> "/"
  | Eq -> "=="
  | Ne -> "!="
  | Lt -> "<"
  | Le -> "<="
  | Gt -> ">"
  | Ge -> ">="
  | And -> "&&"
  | Or -> "||"

(* ## 7.3 ランタイムが提供するエフェクト — 名簿 2 枚

   エフェクトシステムの約束は「**ハンドラの無いエフェクトは起こせない**」
   です。ではプログラムの一番外側では何が起こせるのか。その答えが
   `toplevel_effects` で、第11章の `toplevel_eff` はここから
   **閉じた行** — 尾部が `TRowEmpty`、つまり行変数で伸びない行 — を作ります
   (計画 §7.6)。

   名簿は 2 枚あり、問いが違います (D88)。

   | 名簿 | 問い | 仕様 |
   |---|---|---|
   | `runtime_effects` | ランタイムが実装を持つのはどれか(= ユーザが handle できないのはどれか) | sample.kel:511 |
   | `toplevel_effects` | トップレベルの行に残してよいのはどれか | sample.kel:630 |

   前者は `Console` / `Async` / `Fs` の 3 つ。仕様は印を設けず**名前で**定めると
   明記しており、第11章 §11.23 のハンドル禁止がこの名簿を引きます。
   後者はそれに `Blocking` を足した 4 つです。

   ### 3 つめの種類 — 操作を持たないラベル

   `Console` と `Async` は操作を持ち、その操作は第13章の `with_runtime` が
   実際に捕まえます。`Fs` と `Blocking` は**操作を 1 つも持ちません** (M27)。
   `perform` できる操作が無く、`handle` の節も書けない。型の上にしか
   存在せず、仕事は「その行を持たない文脈から何かを締め出す」ことだけです。

   - `Fs` が締め出すのは、第15章のファイルプリミティブ 4 本です
     (仕様 sample.kel:569-572、D87)。これが無いと 4 本は行なしで型付き、
     `@ {}` と明示したコールバックからファイルを触れました(台帳 V15)。
   - `Blocking` が締め出すのは、`@ Blocking` を付けた FFI バインディングです
     (仕様 sample.kel:767)。落とすのは `pinned` の仕事です。

   ### なぜ `Blocking` は前者の名簿に入らないか

   操作が無いエフェクトでも、`case Blocking.nope() => …` と修飾して書けば
   ハンドル禁止の判定には届きます(修飾節ではその判定が「属しません」より
   先に走ります — 第11章 §11.23)。届くのに入れないのは、入れると診断が
   すり替わるからです。いまは名簿に無いので「操作 nope はエフェクト
   Blocking に属しません」で落ち(実測、`test/blocking_top.t` の bh)、
   これが正確な診断です。入れると同じ入力が「ランタイムが提供するため
   ハンドルできません」になり、操作が無いことを言わなくなります。
   `Fs` を前者に入れたのは、仕様 sample.kel:511 が名指しで禁止しているからで
   (D88)、修飾して `Fs.op` と書いたときだけこの禁止が診断に出ます
   (`test/fs_effect.t` の fsh。文言は D90)。
   かつては `Blocking` がどちらの名簿にも無く、`@ Blocking` の付いた関数を
   `pinned` 無しではトップレベルから呼べませんでした — 仕様 §12 の改訂が
   それを覆しました。`Heap` はどちらの名簿にもいません。2026-09-19 の改訂で
   仕様がその理由を書きました(sample.kel:631-632、D135) — `Heap[h]` は
   リージョン変数を引数に取るラベルで、トップレベルには渡せる `h` が無い。
   `h` を導入するのは `run` だけで、`run` はその `Heap[h]` を自分で消します。

   閉じていることが本質です。トップレベルに `perform print(...)` と書くと、
   行に `Print` を足す余地がないので単一化が失敗し、「エフェクト Print を
   ここでは実行できません」になります。**これは正しい挙動で、
   エフェクトシステムがいちばん働いてほしい場所そのもの**です。
   ここを開いた行にすると、ハンドラを書き忘れたプログラムが素通りします。

   ### なぜ `Async` が入っているか

   `Console` は当然として、`Async` が入っているのには理由があります。
   これが無いと sample.kel:747 の `crunch` をトップレベルから呼べません。
   計画 §2.1 と計画 §11 は「`Async` は v0 では型 + 実行時 no-op」と裁定しており、
   その裁定と「トップレベルから呼べない」が矛盾するからです。
   **型で許すと決めたものは、型が実際に許さなければなりません。**

   ### 守るべき不変条件

   `runtime_effects` のうち**操作を持つもの**(`Console` / `Async`)について、
   その操作の集合は第13章 (builtin.ml) の `with_runtime` が実際に捕まえる
   集合と**一致していなければなりません**。片方だけを足すと、静かに破れます。

   - ここにだけ足す → 型検査は通り、実行時に未捕捉のエフェクトで落ちる
   - `with_runtime` にだけ足す → 実装はあるのに型が禁じる

   `Fs` と `Blocking` はこの不変条件の**外**です。操作が 0 個なので、
   捕まえるべき操作も 0 個 — `with_runtime` に足すものはありません。
   足すべき名前があるかどうかは、名簿ではなく**エフェクト宣言の本体**が
   決めます。空の本体はランタイム側の仕事も空だ、というのが読みどころです。
   名簿は名前しか見ないので、この免除が成り立つのは同梱のプレリュードの
   本体に対してです。`--prelude` は信頼境界の内側(260830-1 の V5)なので、
   差し替えた本体に操作を足せば `Console` に足したときと同じ破れ方をしますが、
   それは差し替えた側の責任で、起動時に照合はしません。

   どちらも「型と実行の食い違い」で、本実装が最も避けようとしている類の
   不具合です。定義点が 1 箇所だという性質は、その 1 箇所を直したときに
   両側が動くという意味であって、**両側を直さなくてよいという意味ではない**
   ことに注意してください。ここは境界であって、境界の向こうは第13章です。

   名簿が 2 枚になったので、関係にも不変条件があります。
   `runtime_effects ⊆ toplevel_effects` — ハンドルを禁じるエフェクトは
   必ずトップレベルに残せなければなりません。禁じたうえで残せなければ、
   そのエフェクトを起こすプログラムがどこにも書けないからです。
   `toplevel_effects` を `runtime_effects` からの連結で定義しているのは、
   この包含を構造で保つためです。 *)

let runtime_effects = [ "Console"; "Async"; "Fs" ]

(* 上の名簿に Blocking を足したもの。包含 runtime_effects ⊆ toplevel_effects を
   構造で保つために連結で定義する *)
let toplevel_effects = runtime_effects @ [ "Blocking" ]
