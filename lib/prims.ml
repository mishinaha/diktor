(* # 第7章 演算子と組み込みエフェクトの表

   本章のファイルは、コメントを除くと 30 行あまりしかない。
   このモジュールは、第1章(syntax.ml)の `bin_op` のほかには何も使わず、
   モジュールの依存関係の**葉**に当たる。
   依存は `open Syntax` の 1 行だけで、宣言表も精緻化木も使わない。
   本章が定めるのは次の 2 つである。

   1. 二項演算子と前置の `-` が、どのクラスのどのメソッドを意味するか
   2. 処理系が最初から提供しているエフェクトはどれか

   どちらも、型検査と実行で一致していなければならない。
   演算子の表は、定義をこの 1 か所に置き、型検査(第11章 elab.ml)、評価(第14章 interp.ml)、
   KIR の書き出し(第18章 ir_write.ml)がどれもここを参照する。
   エフェクトの一覧を参照するのは第11章だけである。
   実行の側(第13章 builtin.ml の `with_runtime`)は一覧を参照しないので、
   両者は人の手で一致させる(§7.3)。
   第5章(tree.ml)の `resolved` が個々のノードについて型検査と実行の一致を保証するのに対し、
   本章の表は言語全体について一致を保証する。

   ## 前章から受け取るもの

   第1章(syntax.ml)の `bin_op`(構文上の演算子)を受け取る。
   第6章(decls.ml)が登録したクラス表(`Add` / `Sub` / `Mul` / `Div` / `Rem` / `Neg` / `Eq` /
   `Ord`)にも依存する。
   ただし、これはコードの依存ではなく、本章に書いたクラス名とメソッド名の文字列が、
   第6章が登録した名前と一致していなければならないという依存である。
   名前が一致しないと、その演算子を型検査したときに、
   第11章の `method_scheme` が内部エラー(`bug`)を出す。

   ## 次章へ渡すもの

   `bin_op_sem` を呼ぶのは、第11章(elab.ml)の `BinOp` の規則、第14章(interp.ml)の `BinOp` の評価、
   第18章(ir_write.ml)の `BinOp` の書き出しである。
   ただし、場合分けの数は同じではない。
   第14章と第18章は、3 つのコンストラクタをそのまま 3 つの分岐で扱う。
   第11章は `!=` を `==` と同じ分岐にまとめるので、分岐は 2 つで済む。
   理由は §7.1 で述べる。
   このほか、第4章(dump.ml)が `show_bin_op` を呼び、
   第11章がエフェクトの 2 つの一覧(§7.3)を参照する。 *)
