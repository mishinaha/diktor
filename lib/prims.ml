(* # 第7章 演算子と組み込みエフェクトの表

   本章のファイルは、コメントを除くと 30 行あまりしかない。
   このモジュールは、第1章(syntax.ml)の `bin_op` のほかには何も使わない**葉**である。
   依存は `open Syntax` の 1 行だけで、宣言表にも精緻化木にも触れない。
   それでも、第11章(elab.ml)と第14章(interp.ml)の両方がこのファイルを読むので、
   両者は同じ答えを見ることになる。
   本章が定めるのは次の 2 つである。

   1. 二項演算子が、どのクラスのどのメソッドを意味するか
   2. 処理系が最初から提供しているエフェクトはどれか

   どちらも、elab と interp で一致していなければならない知識である。
   第5章(tree.ml)の `resolved` は、個々のノードについて一致を保証する。
   本章の表は、言語全体について一致を保証する。
   手段は単純で、定義を 1 か所に置き、両方がそこを読む。

   ## 前章から受け取るもの

   第1章(syntax.ml)の `bin_op`(構文上の演算子)を受け取る。
   もう 1 つ、第6章(decls.ml)が登録したクラス表(`Add` / `Sub` / `Mul` / `Div` / `Eq` / `Ord`)も受け取るが、
   こちらはコードの依存ではなく、名前の一致だけでつながっている。
   本章に書いた文字列と第6章が登録した名前がずれると、
   その演算子を型検査したときに第11章の `method_scheme` が内部エラー(`bug`)を出す。

   ## 次章へ渡すもの

   第11章(elab.ml)の `BinOp` の規則と、第14章(interp.ml)の `BinOp` の評価が `bin_op_sem` を引く。
   ただし、場合分けの仕方は同じではない。
   第14章は 3 つのコンストラクタをそのまま 3 つの分岐で扱う。
   第11章は `!=` を `==` と同じ分岐にまとめるので、分岐は 2 つで済む。
   理由は §7.1 で述べる。
   このほか、第4章(dump.ml)が `show_bin_op` を、第11章がエフェクトの 2 つの名簿を引く。 *)
