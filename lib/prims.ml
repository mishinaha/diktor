(* ## 7.1 演算子は糖衣である — ただし脱糖はしない

   Keleut にユーザ定義演算子はありません。代わりに sample.kel:277-283 が
   「組み込みの演算子が標準ライブラリの型クラスを呼ぶ」と決めています。

   | 演算子 | 意味 |
   |---|---|
   | `+` `-` `*` `/` | `Add.add` `Sub.sub` `Mul.mul` `Div.div` |
   | `==` | `Eq.eq` |
   | `!=` | `Eq.eq` の否定 |
   | `<` `<=` `>` `>=` | `Ord.lt` `Ord.le` `Ord.gt` `Ord.ge` |
   | `&&` `||` | Boolean 組み込み(短絡するため型クラスにできない) |

   つまり演算子は糖衣です。ところが本実装は**パーサで脱糖しません**。
   `BinOp` ノードを AST に残し、elab と interp がこの表を引きます
   (裁定 D9)。理由は 2 つ。

   - **エラーメッセージが演算子を保てる。** 脱糖した木はソースに戻せません。
     `x + y` の診断を「`Add.add` の引数が」ではなく `+` の話として出せる
     余地を残す、というのが D9 の理由づけです(現状の診断は型の不一致を
     述べるところまでで、この余地はまだ使い切っていません)。
   - **2 つの例外が表の中に閉じる。** `&&` / `||` と `!=` は、
     メソッド呼び出しに落とせません(後述)。脱糖する設計だと、この 2 つだけ
     パーサに特別扱いが要ります。表なら 3 番目のコンストラクタで済みます。

   ### なぜ `&&` と `||` は型クラスにできないか

   **短絡するから**です。`a && b` をメソッド呼び出し `and(a, b)` に落とすと、
   呼び出しの前に両辺が評価されます。短絡は評価順序の話で、型クラスは
   値の話なので、そもそも層が違う。だから `OpBool` として組み込みに残し、
   第14章が左辺だけを見て分岐します。両辺 Boolean であることの検査は
   第11章がやります。

   ### なぜ `!=` に専用のクラスを作らないか

   `OpMethodNot` は `Eq.eq` を呼んで結果を否定するだけです。**型の上では
   `!=` は `==` と完全に同一**で、第11章は両者を同じ 1 本の枝で処理します
   — `Eq.eq` のスキーマを具体化して単一化し、その返り型(Boolean)を返す。
   違いは第14章での否定 1 回だけです。

   `Ne` を独立のクラスにすれば「`==` と `!=` が食い違うインスタンス」が
   書けてしまいます。導出のたびに 2 つ書く手間も増える。**書けない設計に
   することで、一致を検査する必要がなくなります。**

   ### この表にいないもの

   単項の `!` は二項演算子ではないので、第1章の AST に専用ノード `Not` が
   あります。行の制限 `\` は組み込み構文(`RecordRestriction`)で、
   これもメソッドではありません。表に入れる基準は
   「二項演算子の形をしていて、意味がクラスメソッドで書けるもの」です。 *)

type op_sem =
  | OpMethod of string * string (* クラス名, メソッド名 *)
  | OpMethodNot of string * string (* Eq.eq の否定(!=) *)
  | OpBool (* Boolean 組み込み(短絡するため型クラスにできない) *)

let bin_op_sem = function
  | Add -> OpMethod ("Add", "add")
  | Sub -> OpMethod ("Sub", "sub")
  | Mul -> OpMethod ("Mul", "mul")
  | Div -> OpMethod ("Div", "div")
  | Eq -> OpMethod ("Eq", "eq")
  | Ne -> OpMethodNot ("Eq", "eq")
  | Lt -> OpMethod ("Ord", "lt")
  | Le -> OpMethod ("Ord", "le")
  | Gt -> OpMethod ("Ord", "gt")
  | Ge -> OpMethod ("Ord", "ge")
  | And | Or -> OpBool

(* ## 7.2 字面へ戻す

   `bin_op_sem` が演算子を意味へ写すのに対し、こちらは字面へ戻します。
   前節で「保てる」と書いた演算子を人に見せるための 1 枚で、`BinOp` を
   AST に残した選択は、この表があって初めて回収できます。

   正直に書いておくと、**いまこの関数を引いている場所はありません**。
   第4章 (dump.ml) は同じ表を自前に持っており、二重定義になっています。
   本章が掲げた原則からすれば、dump 側がここを引くのが正しい形です。
   ドリフトの実害はまだ出ていませんが、演算子を 1 つ足す日に 2 箇所直す
   必要がある、という負債にはなっています。 *)

let show_bin_op = function
  | Add -> "+"
  | Sub -> "-"
  | Mul -> "*"
  | Div -> "/"
  | Eq -> "=="
  | Ne -> "!="
  | Lt -> "<"
  | Le -> "<="
  | Gt -> ">"
  | Ge -> ">="
  | And -> "&&"
  | Or -> "||"

(* ## 7.3 ランタイムが提供するエフェクト

   エフェクトシステムの約束は「**ハンドラの無いエフェクトは起こせない**」
   です。ではプログラムの一番外側では何が起こせるのか。その答えがこの
   2 要素のリストで、第11章の `toplevel_eff` はここから
   **閉じた行** — 尾部が `TRowEmpty`、つまり行変数で伸びない行 — を作ります
   (計画 §7.6)。

   閉じていることが本質です。トップレベルに `perform print(...)` と書くと、
   行に `Print` を足す余地がないので単一化が失敗し、「エフェクト Print を
   ここでは実行できません」になります。**これは正しい挙動で、
   エフェクトシステムがいちばん働いてほしい場所そのもの**です。
   ここを開いた行にすると、ハンドラを書き忘れたプログラムが素通りします。

   ### なぜ `Async` が入っているか

   `Console` は当然として、`Async` が入っているのには理由があります。
   これが無いと sample.kel:529 の `crunch` をトップレベルから呼べません。
   計画 §2.1 §11 は「`Async` は v0 では型 + 実行時 no-op」と裁定しており、
   その裁定と「トップレベルから呼べない」が矛盾するからです。
   **型で許すと決めたものは、型が実際に許さなければなりません。**

   ### 守るべき不変条件

   このリストは、第13章 (builtin.ml) の `with_runtime` が実際に捕まえる
   操作の集合と**一致していなければなりません**。片方だけを足すと、
   静かに破れます。

   - ここにだけ足す → 型検査は通り、実行時に未捕捉のエフェクトで落ちる
   - `with_runtime` にだけ足す → 実装はあるのに型が禁じる

   どちらも「型と実行の食い違い」で、本実装が最も避けようとしている類の
   不具合です。定義点が 1 箇所だという性質は、その 1 箇所を直したときに
   両側が動くという意味であって、**両側を直さなくてよいという意味ではない**
   ことに注意してください。ここは境界であって、境界の向こうは第13章です。 *)

let runtime_effects = [ "Console"; "Async" ]
