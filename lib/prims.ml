(* ## 7.1 演算子は糖衣構文だが脱糖しない

   Keleut にはユーザ定義の演算子がない。
   代わりに sample.kel:365-370 が、
   組み込みの演算子は標準環境の型クラスのメソッドを呼ぶと定めている。

   | 演算子 | 意味 |
   |---|---|
   | `+` `-` `*` `/` `%` | `Add.add` `Sub.sub` `Mul.mul` `Div.div` `Rem.rem` |
   | 前置の `-` | `Neg.neg`(`BinOp` ではなく `Neg` のノード) |
   | `==` | `Eq.eq` |
   | `!=` | `Eq.eq` の否定 |
   | `<` `<=` `>` `>=` | `Ord.lt` `Ord.le` `Ord.gt` `Ord.ge` |
   | `&&` `\|\|` | Boolean の組み込み(短絡評価するので型クラスにできない) |

   このように演算子はメソッド呼び出しの糖衣構文だが、本実装はパーサで脱糖(糖衣構文の展開)をしない。
   `BinOp` ノードを AST に残し、第11章、第14章、第18章がこの表を引く。
   理由は 2 つある。

   - **診断に演算子を出せる。**
     脱糖した木からは、ソースに書かれた演算子が分からない。
     ノードを残しておけば、`x + y` の診断を `Add.add` の引数の誤りとしてではなく、
     `+` の誤りとして出せる。
     ただし、現在の診断は型の不一致を述べるだけで、演算子の表記は使っていない。
   - **2 つの例外をこの表だけで扱える。**
     `&&` / `||` と `!=` は、メソッド呼び出し 1 つには置き換えられない。
     理由は下の 2 つの小節で述べる。
     脱糖する設計では、この 2 つだけをパーサで特別に扱う必要がある。
     表なら、`OpMethod` のほかに `OpMethodNot` と `OpBool` の 2 つのコンストラクタを置くだけで済む。

   ### `&&` と `||` を型クラスにしない理由

   `&&` と `||` は短絡評価する。
   `a && b` をメソッド呼び出し `and(a, b)` に置き換えると、呼び出しの前に両辺が評価されてしまう。
   短絡評価は右辺を評価するかどうかを決める規則で、
   評価の済んだ引数を受け取るメソッドでは実現できない。
   そこで `OpBool` として組み込みに残し、第14章が左辺の値だけを見て、
   右辺を評価するかどうかを決める。
   両辺が Boolean であることは第11章が検査する。

   ### `!=` に専用のクラスを作らない理由

   `OpMethodNot` は `Eq.eq` を呼んで結果を否定するだけである。
   `!=` と `==` は型付けが同じなので、第11章は両者を 1 つの分岐で処理する。
   その分岐は `Eq.eq` の型スキームを具体化して両辺の型と単一化し、返り値の型(Boolean)を返す。
   違いは、実行する側(第14章と第18章)が結果を 1 回否定することだけである。

   `Ne` を独立したクラスにすると、`==` と `!=` の結果が食い違うインスタンスを書けてしまう。
   導出も、型ごとに `Eq` と `Ne` の 2 つを作らなければならなくなる。
   食い違うインスタンスを書けない設計にしておけば、一致を検査する必要がない。

   ### この表にないもの

   単項の `!` と前置の `-` は二項演算子ではないので、
   第1章の AST に専用のノード `Not` と `Neg` がある。
   `Not` は Boolean の組み込みである。
   `Neg` はメソッド呼び出しで、下の `neg_method`(`Neg.neg`)を呼ぶ。
   フィールドの除去 `\` は組み込みの構文(`RecordRestriction`)で、これもメソッドではない。
   この表に入れる基準は、二項演算子の形をしていることである。
   そのため、意味をクラスのメソッドで書けない `&&` と `||` も、`OpBool` として表に入れる。 *)

type op_sem =
  | OpMethod of string * string (* クラス名, メソッド名 *)
  | OpMethodNot of string * string (* Eq.eq の否定(!=) *)
  | OpBool (* Boolean の組み込み(短絡評価するので型クラスにできない) *)

let bin_op_sem = function
  | Add -> OpMethod ("Add", "add")
  | Sub -> OpMethod ("Sub", "sub")
  | Mul -> OpMethod ("Mul", "mul")
  | Div -> OpMethod ("Div", "div")
  | Rem -> OpMethod ("Rem", "rem")
  | Eq -> OpMethod ("Eq", "eq")
  | Ne -> OpMethodNot ("Eq", "eq")
  | Lt -> OpMethod ("Ord", "lt")
  | Le -> OpMethod ("Ord", "le")
  | Gt -> OpMethod ("Ord", "gt")
  | Ge -> OpMethod ("Ord", "ge")
  | And | Or -> OpBool

(* ## 7.2 演算子をソース上の表記に戻す

   `bin_op_sem` が演算子の意味を返すのに対し、`show_bin_op` は演算子のソース上の表記を返す。
   `BinOp` を AST に残してあるので、演算子を表示するときはこの関数を使える。

   この関数を呼ぶのは第4章(dump.ml)の `BinOp` のダンプだけで、
   `--dump-ast` はこの関数が返す文字列で演算子を出力する。
   第4章は `bin_op` の表記の表を持たないので、
   `bin_op` を表記に戻す表はこの 1 つだけである。
   トークンの表記は、これとは別に第2章(lexer.ml)の §2.12 の `show_token` が持つ。
   診断に演算子の表記を出す場合も、この関数を使えば `--dump-ast` と同じ表記になる。 *)

let show_bin_op = function
  | Add -> "+"
  | Sub -> "-"
  | Mul -> "*"
  | Div -> "/"
  | Rem -> "%"
  | Eq -> "=="
  | Ne -> "!="
  | Lt -> "<"
  | Le -> "<="
  | Gt -> ">"
  | Ge -> ">="
  | And -> "&&"
  | Or -> "||"

(* ## 7.3 ランタイムが提供するエフェクトの 2 つの一覧

   エフェクトシステムでは、ハンドラのないエフェクトは起こせない。
   プログラムの最も外側で起こせるエフェクトを決めるのが `toplevel_effects` で、
   第11章 §11.30 の `toplevel_eff` はこの一覧から**閉じた行**を作る。
   閉じた行とは、行の末尾が `TRowEmpty` で、行変数によってラベルが増えることのない行である。

   トップレベルの行は閉じていなければならない。
   トップレベルに `perform print(...)` と書くと、
   閉じた行には `Print` を追加できないので単一化が失敗し、
   `エフェクト Print をここでは実行できません` で始まる型エラーになる。
   エフェクトシステムは、ハンドラを書き忘れたプログラムをこうして検出する。
   トップレベルの行を開いた行にすると、こうしたプログラムが型検査に通ってしまう。

   一覧は 2 つあり、それぞれ別のことを決める。

   | 一覧 | 決めること | 仕様 |
   |---|---|---|
   | `runtime_effects` | ランタイムが実装を持ち、ユーザがハンドルできないエフェクト | sample.kel:538 |
   | `toplevel_effects` | トップレベルの行に残してよいエフェクト | sample.kel:659 |

   `runtime_effects` に入っているのは `Console` だけである。
   仕様は、ハンドルできないエフェクトを特別な注釈ではなく名前で定めている。
   第11章 §11.23 のハンドル禁止の判定がこの一覧を参照する。
   `toplevel_effects` は、`runtime_effects` に `Blocking` を加えた 2 つである。

   ### 操作を持たないラベル

   `Console` は操作を持ち、その操作は第13章 §13.6 の `with_runtime` が受け取って処理する。
   `Blocking` は操作を 1 つも持たない。
   `perform` できる操作がなく、`handle` の節も書けない。
   `Blocking` は型の上にしか存在しない。
   役目は、行に `Blocking` を持たない文脈から、特定の関数を呼べなくすることだけである。
   呼べなくなるのは、`@ Blocking` を付けた `extern`(C リンケージで `@` を省略したものを含む)の
   バインディングである(仕様 sample.kel:496、:796)。
   このラベルを行から取り除くのは、組み込みの `pinned` である。

   ### `Blocking` を `runtime_effects` に入れない理由

   `Blocking` は操作を持たないので、型検査に通る `handle` の節は書けず、ハンドルを禁じる必要がない。
   ただし、`case Blocking.nope() => …` のように、
   存在しない操作を修飾した節をソースに書くことはできる。
   修飾した節では、第11章 §11.23 がハンドル禁止の判定を、
   操作がそのエフェクトに属するかどうかの判定より先に行うので、この節もハンドル禁止の判定まで進む。
   そのため、`Blocking` を `runtime_effects` に入れると、この入力の診断が変わる。
   一覧に入れていないので、この入力は `操作 nope はエフェクト Blocking に属しません` という型エラーになる。
   これが正確な診断で、`test/blocking_top.t` が `bh.kel` の期待出力としてこの診断を固定している。
   一覧に入れると、同じ入力のエラーが、
   ランタイムが提供するのでハンドルできないというメッセージに変わり、
   操作がないことが伝わらなくなる。

   `Blocking` は `toplevel_effects` には入っているので、`@ Blocking` の付いた関数は、
   `pinned` を使わずにトップレベルから呼べる(仕様 §12、sample.kel:809)。
   `Heap` はどちらの一覧にもない。
   その理由は仕様に書いてある(sample.kel:660-661)。
   `Heap[h]` はリージョン変数を引数に取るラベルで、トップレベルには渡せる `h` がない。
   `h` を導入するのは `run` だけで、`run` はその `Heap[h]` を自分で取り除く。

   ### 守るべき不変条件

   `runtime_effects` のうち操作を持つもの(`Console`)について、
   その操作の集合は、第13章(builtin.ml)の `with_runtime` が受け取る操作の集合と一致していなければならない。
   片方だけを変えると、Diktor のビルドではエラーにならないまま、型検査と実行が食い違う。

   - この一覧にだけエフェクトを追加すると、型検査に通り、
     実行時にその操作を受け取るハンドラがなくてエラーになる
   - `with_runtime` にだけ操作を追加すると、実装はあるのに型検査がその操作を拒否する

   `Blocking` はこの不変条件の対象外である。
   操作が 0 個なので、`with_runtime` が受け取るべき操作もない。
   `with_runtime` が受け取るべき操作は、一覧ではなくエフェクトの宣言の本体で決まる。
   一覧が持つのはエフェクトの名前だけだからである。
   `Blocking` は第6章 §6.11 の組み込みの登録が宣言する。
   プレリュードやユーザが操作を加えて宣言し直すと、標準環境の名前の再宣言として型エラーになる。
   一方、`Console` はプレリュードが宣言する。
   `--prelude` で差し替えたプレリュードが `Console` に操作を追加すると、
   一覧にだけエフェクトを追加したときと同じ食い違いが起きる。
   Diktor は、差し替えるプレリュードを信頼できるものとして扱い、起動時にこの一致を検査しない。
   一致させるのは、プレリュードを差し替える人の責任である。

   上の 2 つの食い違いは、どちらも型検査と実行の不一致で、
   本実装が最も避けようとしている種類のバグである。
   一覧を 1 か所に置いたので、型検査の側はこの一覧を直せば変わる。
   しかし `with_runtime` はこの一覧を参照しないので、実行の側は第13章も直さなければ変わらない。

   2 つの一覧の間にも不変条件がある。
   `runtime_effects ⊆ toplevel_effects`、つまりハンドルを禁じるエフェクトは、
   トップレベルに残せなければならない。
   ハンドルを禁じたうえにトップレベルにも残せなければ、
   そのエフェクトを起こすプログラムをどこにも書けないからである。
   `toplevel_effects` を `runtime_effects` との連結で定義しているのは、
   定義の形からこの包含が必ず成り立つようにするためである。 *)

(* 前置の - が呼ぶメソッド。第11章、第14章、第18章が同じ組を使う *)
let neg_method = ("Neg", "neg")

let runtime_effects = [ "Console" ]

(* 上の一覧に Blocking を加えたもの。包含 runtime_effects ⊆ toplevel_effects が
   必ず成り立つように、連結で定義する *)
let toplevel_effects = runtime_effects @ [ "Blocking" ]
