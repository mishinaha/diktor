(* ## 7.1 演算子は糖衣だが脱糖しない

   Keleut は利用者定義の演算子を持たない。
   代わりに sample.kel:364-369 が、
   組み込みの演算子は標準ライブラリの型クラスのメソッドを呼ぶと定めている。

   | 演算子 | 意味 |
   |---|---|
   | `+` `-` `*` `/` | `Add.add` `Sub.sub` `Mul.mul` `Div.div` |
   | `==` | `Eq.eq` |
   | `!=` | `Eq.eq` の否定 |
   | `<` `<=` `>` `>=` | `Ord.lt` `Ord.le` `Ord.gt` `Ord.ge` |
   | `&&` `\|\|` | Boolean 組み込み(短絡するため型クラスにできない) |

   このように演算子は糖衣だが、本実装はパーサで脱糖しない。
   `BinOp` ノードを AST に残し、elab と interp がこの表を引く。
   理由は 2 つある。

   - **エラーメッセージで演算子を保てる。**
     脱糖した木からは、ソースに書かれた演算子に戻れない。
     ノードを残しておけば、`x + y` の診断を `Add.add` の引数の話ではなく `+` の話として出せる。
     ただし、現在の診断は型の不一致を述べるだけで、演算子の字面は使っていない。
   - **2 つの例外を表の中に閉じ込められる。**
     `&&` / `||` と `!=` は、メソッド呼び出しに落とせない(後述)。
     脱糖する設計では、この 2 つだけパーサで特別に扱う必要がある。
     表なら、`OpMethod` のほかに `OpMethodNot` と `OpBool` の 2 つのコンストラクタを足すだけで済む。

   ### `&&` と `||` を型クラスにしない理由

   `&&` と `||` は短絡する。
   `a && b` をメソッド呼び出し `and(a, b)` に落とすと、呼び出しの前に両辺が評価される。
   短絡は評価順序の問題で、型クラスは値についての仕組みなので、扱う層が違う。
   そこで `OpBool` として組み込みに残し、第14章が左辺だけを見て分岐する。
   両辺が Boolean であることは第11章が検査する。

   ### `!=` に専用のクラスを作らない理由

   `OpMethodNot` は `Eq.eq` を呼んで結果を否定するだけである。
   型の上では `!=` と `==` はまったく同じで、第11章は両者を同じ 1 本の分岐で処理する。
   その分岐は `Eq.eq` のスキーマを具体化して単一化し、その返り値の型(Boolean)を返す。
   違いは第14章での否定 1 回だけである。

   `Ne` を独立したクラスにすると、`==` と `!=` の結果が食い違うインスタンスを書けてしまう。
   導出のたびに 2 つ書く手間も増える。
   食い違いを書けない設計にしておけば、一致を検査する必要がない。

   ### この表に無いもの

   単項の `!` は二項演算子ではないので、第1章の AST に専用のノード `Not` がある。
   フィールドの除去 `\` は組み込みの構文(`RecordRestriction`)で、これもメソッドではない。
   この表に入れる基準は、二項演算子の形をしていることである。
   意味をクラスのメソッドで書けない `&&` と `||` も、`OpBool` として表に入れる。 *)

type op_sem =
  | OpMethod of string * string (* クラス名, メソッド名 *)
  | OpMethodNot of string * string (* Eq.eq の否定(!=) *)
  | OpBool (* Boolean 組み込み(短絡するため型クラスにできない) *)

let bin_op_sem = function
  | Add -> OpMethod ("Add", "add")
  | Sub -> OpMethod ("Sub", "sub")
  | Mul -> OpMethod ("Mul", "mul")
  | Div -> OpMethod ("Div", "div")
  | Eq -> OpMethod ("Eq", "eq")
  | Ne -> OpMethodNot ("Eq", "eq")
  | Lt -> OpMethod ("Ord", "lt")
  | Le -> OpMethod ("Ord", "le")
  | Gt -> OpMethod ("Ord", "gt")
  | Ge -> OpMethod ("Ord", "ge")
  | And | Or -> OpBool

(* ## 7.2 字面へ戻す

   `bin_op_sem` が演算子を意味へ写すのに対し、`show_bin_op` は演算子を字面へ戻す。
   `BinOp` を AST に残してあるので、演算子を人に見せるときはこの関数を使える。

   この関数を呼ぶのは第4章(dump.ml)の `BinOp` のダンプだけで、
   `--dump-ast` の演算子表記はここから出る。
   dump 側は `bin_op` の字面の表を自前では持たないので、
   `bin_op` を字面に戻す表はこの 1 つだけである。
   トークンの字面は、これとは別に第2章(lexer.ml)の §2.12 の `show_token` が持つ。
   診断に演算子の字面を出す場合も、この関数を使えば表記が揃う。 *)

let show_bin_op = function
  | Add -> "+"
  | Sub -> "-"
  | Mul -> "*"
  | Div -> "/"
  | Eq -> "=="
  | Ne -> "!="
  | Lt -> "<"
  | Le -> "<="
  | Gt -> ">"
  | Ge -> ">="
  | And -> "&&"
  | Or -> "||"

(* ## 7.3 ランタイムが提供するエフェクトの 2 つの名簿

   エフェクトシステムでは、ハンドラの無いエフェクトは起こせない。
   プログラムの一番外側で起こせるエフェクトを決めるのが `toplevel_effects` で、
   第11章の `toplevel_eff` はこの名簿から**閉じた行**を作る。
   閉じた行とは、尾部が `TRowEmpty` で、行変数によって伸びない行である。

   トップレベルの行は閉じていなければならない。
   トップレベルに `perform print(...)` と書くと、行に `Print` を足す余地が無いので単一化が失敗し、
   「エフェクト Print をここでは実行できません」で始まるエラーになる。
   これは、ハンドラを書き忘れたプログラムをエフェクトシステムが捕まえる典型的な場面である。
   トップレベルの行を開いた行にすると、こうしたプログラムが型検査を素通りする。

   名簿は 2 つあり、答える問いが違う。

   | 名簿 | 問い | 仕様 |
   |---|---|---|
   | `runtime_effects` | ランタイムが実装を持つのはどれか(利用者がハンドルできないのはどれか) | sample.kel:534 |
   | `toplevel_effects` | トップレベルの行に残してよいのはどれか | sample.kel:655 |

   `runtime_effects` は `Console` / `Async` / `Fs` の 3 つである。
   仕様は特別な印を設けず、この 3 つを名前で定めている。
   第11章 §11.23 のハンドル禁止の判定がこの名簿を引く。
   `toplevel_effects` は、`runtime_effects` に `Blocking` を足した 4 つである。

   ### 操作を持たないラベル

   `Console` と `Async` は操作を持ち、その操作は第13章の `with_runtime` が実際に捕まえる。
   `Fs` と `Blocking` は操作を 1 つも持たない。
   `perform` できる操作が無く、`handle` の節も書けない。
   この 2 つは型の上にしか存在せず、そのラベルを行に持たない文脈から、
   特定の関数の呼び出しを締め出すことだけが役目である。

   - `Fs` が締め出すのは、第15章のファイルプリミティブ 4 つである(仕様 sample.kel:594-597)。
     `Fs` が無ければ 4 つは行を持たずに型が付き、
     `@ {}` と明示したコールバックの中からもファイルを操作できてしまう。
   - `Blocking` が締め出すのは、`@ Blocking` を付けた FFI バインディングである(仕様 sample.kel:792)。
     このラベルを行から取り除くのは `pinned` の仕事である。

   `runtime_effects` の 3 つのうち、操作を持たないのは `Fs` だけである。
   仕様も「ランタイムが実装を持つ」を 2 通りに分けている(sample.kel:535-537)。
   1 つは操作の実装をランタイムが持つもの(`Console` / `Async`)で、
   もう 1 つは操作を持たず、ランタイムのプリミティブだけがそのラベルを行に載せるもの(`Fs`)である。

   ### `Blocking` を `runtime_effects` に入れない理由

   操作が無いエフェクトでも、`case Blocking.nope() => …` と修飾して書けば、
   ハンドル禁止の判定には届く。
   修飾した節では、第11章 §11.23 がハンドル禁止の判定を、
   操作がそのエフェクトに属するかどうかの判定より先に行うからである。
   それでも `Blocking` を入れないのは、入れると診断が変わってしまうからである。
   名簿に無いので、この入力は「操作 nope はエフェクト Blocking に属しません」というエラーになる。
   これが正確な診断で、`test/blocking_top.t` の bh がこの結果を固定している。
   名簿に入れると、同じ入力のエラーが、ランタイムが提供するのでハンドルできないという文面に変わり、
   操作が無いことを伝えなくなる。

   `Fs` を `runtime_effects` に入れているのは、
   仕様 sample.kel:534 が名指しでハンドルを禁止しているからである。
   `Fs` は操作を持たないので、非修飾の節では候補に挙がらない。
   `Fs.op` と修飾して書いたときだけ、この禁止が診断に出る(`test/fs_effect.t` の fsh)。

   `Blocking` は `toplevel_effects` には入っているので、`@ Blocking` の付いた関数は、
   `pinned` を使わずにトップレベルから呼べる(仕様 §12、sample.kel:805)。
   `Heap` はどちらの名簿にも無い。
   その理由は仕様が書いている(sample.kel:656-657)。
   `Heap[h]` はリージョン変数を引数に取るラベルで、トップレベルには渡せる `h` が無い。
   `h` を導入するのは `run` だけで、`run` はその `Heap[h]` を自分で取り除く。

   ### `Async` を名簿に入れる理由

   `toplevel_effects` に `Async` が無いと、sample.kel:772 の `crunch` をトップレベルから呼べない。
   型の上で `@ Async` を持つ関数を認める以上、トップレベルの行も `Async` を認めていなければ、
   その関数を呼べる場所が無くなる。
   Diktor は `Async` を型の上では本物のエフェクトとして扱い、実行時には何もしない。
   第13章の `with_runtime` は、`yield_` と `sleep` をその場で再開する。

   ### 守るべき不変条件

   `runtime_effects` のうち操作を持つもの(`Console` / `Async`)について、
   その操作の集合は、第13章(builtin.ml)の `with_runtime` が実際に捕まえる集合と一致していなければならない。
   片方だけに足すと、何のエラーも出ないまま一致が崩れる。

   - この名簿にだけ足すと、型検査は通り、実行時に未捕捉のエフェクトで落ちる
   - `with_runtime` にだけ足すと、実装はあるのに型が禁じる

   `Fs` と `Blocking` はこの不変条件の対象外である。
   操作が 0 個なので捕まえるべき操作も 0 個で、`with_runtime` に足すものが無い。
   足すべき操作があるかどうかは、名簿ではなくエフェクト宣言の本体が決める。
   本体が空なら、ランタイム側の仕事も空である。
   ただし名簿は名前しか見ないので、
   この免除が成り立つのは同梱のプレリュードの本体に対してだけである。
   `--prelude` で差し替えるプレリュードは、信頼境界の内側にあるものとして扱う。
   差し替えた本体に操作を足すと `Console` に足したときと同じ崩れ方をするが、
   Diktor は起動時にこれを照合せず、差し替えた側の責任とする。

   名簿と `with_runtime` の一方だけに足したときの 2 つの崩れ方は、
   どちらも型と実行の食い違いで、本実装が最も避けようとしている種類の不具合である。
   名簿を 1 か所に置いたので、型検査の側はこの名簿を直せば追従する。
   しかし `with_runtime` はこの名簿を読まないので、実行の側は第13章を直さなければ変わらない。

   2 つの名簿の関係にも不変条件がある。
   `runtime_effects ⊆ toplevel_effects`、つまりハンドルを禁じるエフェクトは、
   トップレベルに残せなければならない。
   ハンドルを禁じたうえにトップレベルにも残せなければ、
   そのエフェクトを起こすプログラムをどこにも書けないからである。
   `toplevel_effects` を `runtime_effects` との連結で定義しているのは、
   この包含を構造で保つためである。 *)

let runtime_effects = [ "Console"; "Async"; "Fs" ]

(* 上の名簿に Blocking を足したもの。包含 runtime_effects ⊆ toplevel_effects を
   構造で保つために連結で定義する *)
let toplevel_effects = runtime_effects @ [ "Blocking" ]
