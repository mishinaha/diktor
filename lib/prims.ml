(* # 第7章 — 演算子と組み込みエフェクトの表

   本章のファイルは、コードだけなら 40 行そこそこです。第1章 (syntax.ml) の
   `bin_op` 以外には何も要らない**葉**で(計画 §8.1 の「宣言のみの葉」)、
   `open Syntax` の 1 行が唯一の依存。宣言表にも精緻化木にも触りません。
   それでいて、型検査器と評価器の両方が同じ答えを見るための要になっています。
   ここに書いてあるのは 2 つだけ。

   1. 二項演算子が、どのクラスのどのメソッドを意味するか
   2. 処理系が最初から提供しているエフェクトはどれか

   どちらも「elab と interp が一致していなければならない知識」です。
   第5章 (tree.ml) の `resolved` が**個々のノードについて**一致を保証する
   仕組みだったのに対し、こちらは**言語全体について**一致を保証する仕組みで、
   手段は素朴です。定義を 1 箇所に置き、両方がそこを読む。

   > 二者が一致しなければならない知識は、二者のどちらにも置かない。

   ## 前章から受け取るもの

   第1章 (syntax.ml) の `bin_op`(構文の演算子)。それと、第6章 (decls.ml) が
   登録したクラス表(`Add` / `Sub` / `Mul` / `Div` / `Eq` / `Ord`)ですが、
   後者はコードの依存としてではなく**名前の一致**だけで受け取ります。
   ここに書いた文字列と第6章が登録した名前がずれたら、その場で壊れます。

   ## 次章へ渡すもの

   第11章 (elab.ml) の `BinOp` 規則と、第14章 (interp.ml) の `BinOp` 評価。
   どちらも `bin_op_sem` を引きますが、開き方は同じではありません。第14章は
   3 つのコンストラクタをそのまま 3 分岐に開き、第11章は `!=` を `==` と
   同じ枝にまとめるので 2 分岐で済みます。理由は §7.1 に書きます。 *)
