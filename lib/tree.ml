(* # 第5章 — 精緻化木: 型検査は木への書き込み

   第3章 (parser.mly) が返す AST は、まだ「ソースに書いてあること」しか
   持っていません。ところが実行するには、書いていないことをいくつも
   知らなければなりません。

   | 実行に要る知識 | 決まらない理由 |
   |---|---|
   | `perform write(x)` はどの操作か | `Console.write` と `File.write` が同居 (D22) |
   | `Point(y = 2, x = 1)` の並び順 | ラベル指定で並べ替えられる |
   | `handle` の節の種類 | 構文上はどれも `match` と同じ節 |
   | `1` は Int32 か Int64 か Float64 か | 既定化が決める (D8, D13) |

   これらはすべて型検査が決めます。そこで本実装の型検査は、決めた答えを
   **木そのものに書き戻します**。真偽を返す判定器ではなく、入力の木を
   実行できる木へ育てる関数だと考えるわけです。この育てる操作を
   精緻化 (elaboration) と呼び、本章のファイルは「育った枝を挿す場所」
   だけを用意します。

   > 型検査器は判定器ではない。木を育てる関数である。

   この設計を採ると、第14章 (interp.ml) が名前解決を一切やり直さずに
   済みます。採らなかった場合に何が起きるかもはっきりしています。elab と
   interp が同じ解決規則を二重に実装し、片方だけ直された日に静かにずれる。
   「型検査が見ていたエフェクトと実行時に飛ぶエフェクトが違う」という種類の
   バグは、再現例を作るのが難しく、直すのはもっと難しい。

   ## 前章から受け取るもの

   第1章 (syntax.ml) の `Syntax.Make` ファンクタ — AST をノード付随データで
   パラメータ化したもの — と、第3章 (parser.mly) が組み立てた木。

   ## 次章へ渡すもの

   `Tree.Tree`。精緻化用のデータを載せて具体化した AST 型です。精緻化木を
   直に扱う 5 つのファイル — 第6章 (decls.ml)・第10章 (exhaust.ml)・
   第11章 (elab.ml)・第12章 (value.ml)・第14章 (interp.ml) — は、どれも
   `module T = Tree.Tree` の 1 行から始まります。木を触らない章
   (第7章 (prims.ml) や第8章 (unify.ml) など)はこの行を持ちません。 *)
open Aux

(* ## 5.1 elab から interp への窓口

   `resolved` は「型検査が解いた答えのうち、実行時にはもう解けないもの」の
   一覧です(計画 §4.2)。ここに列挙されている 5 つは、どれも情報が型検査の
   最中にしか揃っていません。エフェクト行の最左は実行時には残っていないし、
   コンストラクタのフィールド順は宣言表を引かないと分からないし、節の分類は
   宣言されたエフェクトの操作集合を知って初めてできます。

   書く側は第11章 (elab.ml)、読む側は第14章 (interp.ml) と第10章
   (exhaust.ml) です。行き先を先に表にしておきます。

   | 値 | 書く場所 | 読む場所 | 読み手がそれで何をするか |
   |---|---|---|---|
   | `ROp` | `Perform`・操作節 | 第14章 | 飛ばすラベル、ハンドラの節引き |
   | `RReturnClause` | `return` 節 | 第14章 | 正常終了時に走らせる節の選別 |
   | `RCancelClause` | `handle` の `cancel` 節 | 第14章 | 巻き戻し時に走らせる節の選別 |
   | `RCtor` | `Construct`・裸の ctor 参照 | 第14章 | 格納位置と、引数ゼロ ctor の値 |
   | `RCtorPat` | `PCtor` | 第14章・第10章 | 照合するフィールドと、欠落フィールドの補完 |

   ### ROp — 完全操作名まで解いておく

   Keleut は操作名の重複宣言を許します(D22。sample.kel 自身が `Console.write`
   と `File.write` を両方宣言しています)。したがって `perform write(x)` の
   `write` がどちらなのかは、その地点のエフェクト行を見ないと決まりません。
   規則は「行の最左、つまり最も内側のハンドラを優先」で、これは Scoped Labels
   の最左一致とも実行時の最内捕捉とも一致します(実装記録 260829-2 の乖離 3)。

   解決の結果は完全名 — `Console.write` のような文字列を intern した oid —
   として `ROp` に入ります。第14章はこの oid をそのまま OCaml の
   エフェクトに載せて飛ばし、ハンドラ側も oid の一致だけを見ます。
   **実行時に名前解決は 1 回も起きません。**

   ### RReturnClause / RCancelClause — 節の分類も型検査の仕事

   `handle` の節は構文上ただのパターン節です。どれが操作節でどれが `return` /
   `cancel` かは、頭のコンストラクタ名を宣言表と突き合わせて初めて分かります。
   分類を第11章が済ませてここへ書くので、第14章は `get_resolved` の値を
   等値比較するだけで 3 種類を選り分けられます。

   ### RCtor と RCtorPat — 対応表の向きが逆なのには理由がある

   `RCtor` の `int array` は添字が実引数位置、値がフィールド位置です。式の
   コンストラクタ適用は全フィールド必須(欠落はエラー)なので、実引数側が
   全フィールドを覆い、option が要りません。第14章はソース順に引数を評価し、
   格納先だけをこの表で付け替えます。**評価順はソースのまま、格納順は宣言の
   まま。** 副作用のある引数をラベル指定で並べ替えて書いても、評価順序は
   読んだとおりになります。

   `RCtor` が付くのは `Construct` ノードだけではありません。`None` のような
   引数ゼロのコンストラクタは `Ident` として構文解析されるので、第11章は
   `Ident` の経路からも同じ `elab_construct` を呼び、その `Ident` ノードにも
   `RCtor` を書きます(対応表は長さ 0 の配列)。第14章はローカルにも大域にも
   その名前が見つからなかったときのフォールバックとしてこの `RCtor` を引き、
   フィールド 0 個の値をその場で作ります。**裸のコンストラクタ参照が
   「未束縛の変数」にならないのは、この 1 本の経路のおかげ**です。

   `RCtorPat` の `int option array` は逆向きで、添字がフィールド位置、値が
   実引数位置です。パターンはフィールドを省略できるので `None` が要ります。
   第10章 (exhaust.ml) はこの `None` を `IWild` に変換してから行列へ載せます
   — 計画 §7.5 の「ラベル指定パターンの欠落フィールドは `PWildcard` で
   補ってから行列に載せる」は、この 1 行に落ちています。

   片方を持って逆写像を計算すれば済みそうに見えますが、そうしません。
   逆写像を作る側でラベル探索と欠落補完の規則をもう一度書くことになり、
   それはこのファイルが存在する理由そのもの(二重実装のドリフト)だからです。
   向きが違うのは需要が違うからでもあります。式は「引数を順に評価して置き場所
   を知りたい」、パターンは「フィールドを順に照合して部分パターンを知りたい」。 *)
type resolved =
  | ROp of oid (* perform / handle 操作節: 完全操作名 Console.write の oid *)
  | RReturnClause (* handle の return 節 *)
  | RCancelClause (* handle の cancel 節 *)
  | RCtor of oid * oid * int array (* Construct: data, ctor, 実引数位置 → フィールド位置 *)
  | RCtorPat of oid * oid * int option array (* PCtor: data, ctor, フィールド位置 → 実引数位置(None = 省略) *)

(* ## 5.2 ノードに付く 4 つのもの

   `ElabData.t` が AST の全ノードに 1 つずつ付きます。中身は 4 つ。

   - `oid` — ノードの同一性。物理等価 (`==`) に頼らずにノードを指せます。
   - `loc` — ソース位置。**パーサが必ず埋めます**。
   - `ty_field` — 型検査が決めた型。`None` は「まだ育っていない」印。
   - `resolved` — §5.1 の解決結果。

   `allocate` が受け取るのは `loc` だけで、残りは `None` から始まります。
   ノードを作るのは第3章 (parser.mly) であって型検査ではないからです。
   型検査はすでに在るノードの空欄を埋めていくだけ、という役割分担が
   この 1 行に現れています。

   ### 可変フィールドである必要

   型を木に書き戻す設計は、一般化 (generalize) が**その場書き換え**で
   あることと組になっています(計画 §7.2)。`set_ty` 済みの型と、その後で
   一般化される型変数とは同じ `ref` を共有しており、共有が切れないからこそ
   「後から一般化した結果」が木の側にも反映されます。一般化が新しい型を
   返す実装だったら、木に書いた型は一般化前の古い型のまま取り残されます。

   実際にこの経路を使うのは数値リテラルです。`1` の型は最初 `Integral` 述語
   つきの新変数で、既定化 (D8) が最後に Int32 へ落とします。第14章は評価の
   たびに `get_ty` を引いて `Int32.of_string` か `Int64.of_string` か
   `float_of_string` かを選ぶ — つまり**既定化の結果は木を通って評価器に
   届きます**(D13 の裁定が「値化は評価時に elab の解決型を見て」と書いている
   のはこのことです)。

   ### loc は配線済み

   `loc` は型エラーメッセージに**繋がっています**(E1 / D53)。第11章の
   `at_node` が `loc_of` で span を取り出し、位置なしの `Type_error` に
   最内ノードの位置を貼って `Type_error_at` として投げ直します。MiniLang
   §17 が「型に出所を持たせるのは実用上は最重要の改善点」と書いていた、
   その配線です。`data` / `oid_of` に呼び出し側が無いのは変わりません —
   `data` はファンクタ越しに `ElabData.t` を取り出す唯一の口、`oid_of` は
   ノードの同一性が要る日のための一般アクセサとして意図的に残してあり、
   v0 の実装に読み手はいません(E8 の裁定)。 *)
module ElabData = struct
  type t = {
    oid : oid;
    loc : Location.span;
    mutable ty_field : Syntax.Type.ty option;
    mutable resolved : resolved option;
  }

  let allocate loc = { oid = new_oid (); loc; ty_field = None; resolved = None }
end

(* ## 5.3 なぜこの木が独立したファイルなのか

   理由は 2 つあります。

   **1. 依存の循環を切るため。** この定義が第11章 (elab.ml) にあると、
   評価器も網羅性検査も木を触るために elab.ml へ依存します。elab.ml が
   いつか interp.ml の何かを使いたくなった瞬間に循環し、そこから抜けるには
   結局この分離をやることになります。だから最初から**葉**に置きます
   (計画 §7.1)。依存は一方向です。木を触る側 — 第4章 (dump.ml)、第6章
   (decls.ml)、第10章 (exhaust.ml)、第11章 (elab.ml)、第12章 (value.ml)、
   第14章 (interp.ml)、第16章 (driver.ml) — はこのファイルへ向き、
   このファイルはそのどれにも向きません。tree.ml 自身が向くのは、木の定義に
   要る素材 3 つ — 第1章 (syntax.ml) の `Syntax.Make`、`Location.span`、
   `Aux` の `new_oid` / `bug` — だけです。**葉と呼んでいるのは
   「何にも依存しない」という意味ではなく、「切りたい循環の相手に依存しない」
   という意味**です。

   **2. パーサの木と型検査の木を同じ型にするため。** ここが OCaml の
   ファンクタの性質に効いています。`Syntax.Make` は**アプリカティブ
   ファンクタ**なので、`Syntax.Make (ElabData)` を別々の場所で適用しても
   同じ型になります。第16章 (driver.ml) は `Parser.Make (Tree.ElabData)` を
   作り、このファイルは `Syntax.Make (ElabData)` を作りますが、両者の `exp` は
   同一の型です。だからパーサが返した木をそのまま型検査に渡せます。

   もし `Syntax.Make` がジェネレーティブ(`()` を取る形)だったら、適用ごとに
   別の型が生まれ、パーサの木を elab の木へ写す変換関数 — AST 全ケース分 —
   を書く羽目になっていました。これは計画時に実機で確かめてあります。 *)
module Tree = Syntax.Make (ElabData)

(* ## 5.4 アクセサ — 不変条件はここで守る

   タプルの第 1 要素がノード付随データ、第 2 要素が構文そのもの、という形が
   全ノードで共通なので、アクセサはどれも `(d, _)` のパターン 1 つで書けます。

   目を留めるべきは `get_ty` が `None` を `bug` にしていることです。これは
   「精緻化されていない木を評価してはならない」という不変条件の表明で、
   ユーザのプログラムがどれだけ変でも起きてはいけない事態、つまり処理系側の
   バグを意味します。だから型エラー (`Type_error`) ではなく `bug`(`Panic`)を
   投げます。第16章 (driver.ml) はこれを実行時エラーと同じ終了コードに落とし
   ますが、メッセージには `[BUG]` が前置され、ユーザのプログラムの誤りでは
   ないことがはっきりします。

   この不変条件が守れているのは、第11章の `elab_exp` が**必ず 1 箇所で**
   `set_ty` を通る形に書かれているからです。式の種類ごとに書き忘れられる形に
   していたら、書き忘れた枝だけが実行時に落ちる — しかも落ちるのは型検査から
   遠く離れた評価器の中、という最悪のデバッグになります。

   > 空欄を残せる設計にしない。空欄は必ず、遠くで見つかる。 *)
let data (d, _) = d

let loc_of (d, _) = d.ElabData.loc

let oid_of (d, _) = d.ElabData.oid

let get_ty (d, _) = match d.ElabData.ty_field with Some t -> t | None -> bug "get_ty: node not elaborated"

let set_ty (d, _) t = d.ElabData.ty_field <- Some t

let get_resolved (d, _) = d.ElabData.resolved

let set_resolved (d, _) r = d.ElabData.resolved <- Some r
